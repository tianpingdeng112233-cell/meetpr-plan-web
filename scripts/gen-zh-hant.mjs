// Development only: OpenCC s2twp + the approved glossary. No converter ships.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import ts from 'typescript'
import * as OpenCC from 'opencc-js'

const convert = OpenCC.Converter({ from: 'cn', to: 'twp' })
const simplify = OpenCC.Converter({ from: 'twp', to: 'cn' })
const glossary = readFileSync('specs/018-zh-hant/GLOSSARY-zh-Hant.md', 'utf8')
const overrides = []
for (const line of glossary.split('## 台湾动作写法别名')[0].split('\n')) {
  if (!line.startsWith('| ')) continue
  const [source, target] = line.split('|').slice(1, 3).map(s => s.trim())
  if (['简体源', '原样'].includes(source) || target === '原样' || source.includes('（reps')) continue
  if (source === '邮箱') { overrides.push(['邮箱', '信箱']); continue }
  if (source.startsWith('周（')) { overrides.push(['周', '週']); continue }
  if (source.startsWith('杆（')) { overrides.push(['杆', target]); continue }
  if (source.startsWith('杠杆（')) { overrides.push(['杠杆', target]); continue }
  if (source === '“ ”' || source === '‘ ’') {
    source.split(' ').forEach((s, i) => overrides.push([s, target.split(' ')[i]])); continue
  }
  const sources = source.split(' / '), targets = target.split(' / ')
  sources.forEach((s, i) => overrides.push([s, targets[i] ?? targets[0]]))
}
// Only these approved UI keys describe repetitions. Other occurrences of 次
// (attempts, sessions, ordinals) must retain their original meaning.
const repsCountKeys = new Set([
  'block.historyHint', 'editor.actualWeightReps', 'editor.repsGuard',
  'editor.cellRepsLabel', 'editor.opaqueSetSettingsHint',
  'stats.context.repsPr', 'stats.board.repsPr',
  'stats.tracking.repsShare', 'stats.tracking.repsDistribution',
  'sheetImport.groupFields.reps',
])
const repsUnitKeys = new Set([
  'common.reps', 'common.countReps', 'block.reps', 'video.repCount',
  'stats.context.setsReps', 'stats.context.repsBest', 'stats.context.repsBestShort',
])
function translationKey(node, section) {
  const path = []
  for (let parent = node.parent; parent; parent = parent.parent) {
    if (ts.isPropertyAssignment(parent)) path.unshift(parent.name.text)
  }
  return [section, ...path].join('.')
}
const protectedNames = ['MeetPR', '微信', 'App Store', 'TestFlight']
const pairs = [...overrides, ...protectedNames.map(s => [s, s])].sort((a, b) => b[0].length - a[0].length)
const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const pattern = new RegExp(pairs.map(([s]) => escape(s)).join('|'), 'g')
const translations = new Map(pairs)
const placeholders = s => s.match(/%\d*\$?(?:@|lld|ld|d|s)|\{\{[^{}]+\}\}|\{[^{}]+\}/g) ?? []
function translate(source, key) {
  if (repsCountKeys.has(key)) source = source.replaceAll('次数', '下數')
  if (repsUnitKeys.has(key)) source = source.replaceAll('次', '下')
  const saved = []
  // Mark glossary spans BEFORE conversion so longer overlapping terms win.
  let result = source.replace(pattern, term => `\uE000${saved.push(translations.get(term)) - 1}\uE001`)
  result = convert(result).replace(/\uE000(\d+)\uE001/g, (_, i) => saved[Number(i)])
  if (source === '邮箱') result = '電子郵件' // standalone input/table label
  if (JSON.stringify(placeholders(source)) !== JSON.stringify(placeholders(result))) throw Error(`Placeholder mismatch: ${source}`)
  return result
}
const writeOutput = (file, data) => {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== data) throw Error(`Stale generated artifact: ${file}`)
  } else writeFileSync(file, data)
}
const banner = '// Generated by npm run gen:zh-hant. Do not edit.\n'
const json = (file, data) => writeOutput(file, JSON.stringify(data, null, 2) + '\n')
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, removeComments: true })
const modules = readdirSync('src/i18n').filter(f => /^strings-(?!zh-hant)[\w-]+\.ts$/.test(f)).sort()
const imports = [], properties = [], declarations = []
for (const file of modules) {
  const source = ts.createSourceFile(file, readFileSync(`src/i18n/${file}`, 'utf8'), ts.ScriptTarget.Latest, true)
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue
    const declaration = statement.declarationList.declarations[0]
    if (!/^zh[A-Z]/.test(declaration.name.getText(source))) continue
    const name = declaration.name.getText(source), suffix = name.slice(2)
    const section = suffix === 'Import' ? 'sheetImport' : suffix[0].toLowerCase() + suffix.slice(1)
    imports.push(`import type { ${name} } from './${file.slice(0, -3)}'`)
    properties.push(`  ${section}: hant${suffix},`)
    const transformed = ts.transform(declaration.initializer, [context => {
      const visit = node => {
        // Literal fragments only: interpolation expressions/user data stay intact.
        if (ts.isStringLiteral(node) && node.parent?.name !== node) return ts.factory.createStringLiteral(translate(node.text, translationKey(node, section)))
        if (ts.isNoSubstitutionTemplateLiteral(node)) return ts.factory.createNoSubstitutionTemplateLiteral(translate(node.text, translationKey(node, section)))
        if (ts.isTemplateHead(node)) return ts.factory.createTemplateHead(translate(node.text, translationKey(node, section)))
        if (ts.isTemplateMiddle(node)) return ts.factory.createTemplateMiddle(translate(node.text, translationKey(node, section)))
        if (ts.isTemplateTail(node)) return ts.factory.createTemplateTail(translate(node.text, translationKey(node, section)))
        return ts.visitEachChild(node, visit, context)
      }
      return node => ts.visitNode(node, visit)
    }])
    declarations.push(`const hant${suffix} = ${printer.printNode(ts.EmitHint.Expression, transformed.transformed[0], source)} satisfies Translations<typeof ${name}>`)
    transformed.dispose()
  }
}
writeOutput('src/i18n/strings-zh-hant.ts', banner + "import type { Translations } from './types'\n" + imports.join('\n') + '\n\n' + declarations.join('\n\n') + '\n\nexport const zhHant = {\n' + properties.join('\n') + '\n}\n')
// Catalog snapshot contains only system names. Unknown/user-authored names are not converted.
const names = new Set(JSON.parse(readFileSync('src/data/exercise-system-names.json', 'utf8')).names)
for (const { alias, canonical } of JSON.parse(readFileSync('src/data/exercise-aliases.json', 'utf8')).aliases) { names.add(alias); names.add(canonical) }
for (const name of ['平板哑铃卧推', '相扑硬拉', '暂停硬拉', '相扑暂停硬拉', '传统暂停硬拉', '二头弯举']) names.add(name)
json('src/i18n/exercise-names-zh-hant.json', Object.fromEntries([...names].sort().map(name => [name, translate(name)])))
// Legacy onboarding copy uses text(zh, en); generated literal fragments let
// tagged templates translate the copy without touching interpolated user data.
const onboarding = {}
for (const file of readdirSync('src/features', { recursive: true }).filter(f => /\.tsx?$/.test(f) && !f.includes('.test.'))) {
  const content = readFileSync(`src/features/${file}`, 'utf8')
  if (!file.startsWith('onboarding/') && !content.includes('/onboarding/text')) continue
  const source = ts.createSourceFile(file, content, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const visit = node => {
    if ((ts.isStringLiteralLike(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) && /[一-鿿]/.test(node.text)) onboarding[node.text] = translate(node.text)
    ts.forEachChild(node, visit)
  }
  visit(source)
}
json('src/i18n/onboarding-zh-hant.json', Object.fromEntries(Object.entries(onboarding).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)))
// Small input-only normalization table; never apply it to notes or display copy.
const inputCharacters = {}, simplifiedOnly = []
for (let cp = 0x3400; cp <= 0x9fff; cp++) {
  const char = String.fromCodePoint(cp), simple = simplify(char)
  if (simple !== char) inputCharacters[char] = simple
}
// Difference of OpenCC's simplified and traditional character alphabets avoids
// flagging shared characters (e.g. 后, 里, 台) that are valid in traditional text.
const characterPairs = OpenCC.Locale.from.cn.flat(Infinity).flatMap(s => s.split('|')).map(s => s.split(' ')).filter(([s]) => [...s].length === 1)
const traditionalAlphabet = new Set(OpenCC.Locale.from.cn.flat(Infinity).flatMap(s => s.split('|')).flatMap(s => s.split(' ').slice(1)).flatMap(s => [...s, ...convert(s)]))
for (const [char, target] of characterPairs) if (char !== target && !traditionalAlphabet.has(char)) simplifiedOnly.push(char)
// 槓 is shared by 杠 and 杆: keep the existing generic 杠 normalization,
// and restore 杆 only where a system name or Latin bar token identifies it.
const inputPhrases = Object.fromEntries(overrides.filter(([s, t]) => s !== t && s !== '杆').map(([s, t]) => [t, s]))
for (const name of JSON.parse(readFileSync('src/data/exercise-system-names.json', 'utf8')).names) {
  if (!name.includes('杆')) continue
  inputPhrases[translate(name)] = name
  for (const [token] of name.matchAll(/[A-Za-z]+杆/g)) {
    for (const variant of [token, token.toLowerCase(), token.toUpperCase()]) inputPhrases[translate(variant)] = variant
  }
}
json('src/i18n/input-zh-hant.json', { characters: inputCharacters, phrases: inputPhrases })
json('src/i18n/simplified-only.json', [...new Set(simplifiedOnly)].sort().join(''))
json('src/i18n/glossary-zh-hant.json', { ...Object.fromEntries(overrides.map(([source]) => [source, translate(source)])), '次数（reps 义）': '下數', 'N 次（reps 单位）': 'N 下' })
console.log(`Generated ${declarations.length} dictionaries and ${names.size} exercise names (OpenCC s2twp).`)
