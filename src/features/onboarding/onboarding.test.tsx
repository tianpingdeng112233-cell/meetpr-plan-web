it.each(['coach', 'admin'])('reauthenticates the target email after setup succeeds but login fails over an old %s session', async (role) => {
  localStorage.setItem('mpw.accessToken', 'synthetic-old-access')
  localStorage.setItem('mpw.user', JSON.stringify({ id: 'old-user-a', role }))
  history.replaceState(null, '', `/coach/set-password#email=newcoach%40example.test&token=${'d'.repeat(64)}`)
  let loginAttempts = 0
  const fetcher = vi.fn(async (url: string, _init?: RequestInit) => {
    if (url.endsWith('/auth/email/reset')) return new Response(null, { status: 204 })
    if (url.endsWith('/auth/email/login')) {
      if (++loginAttempts === 1) throw new Error('network interrupted')
      return new Response(JSON.stringify({ user: { id: 'new-user-b', role: 'coach', email: 'newcoach@example.test' }, accessToken: 'synthetic-new-access', refreshToken: 'synthetic-new-refresh' }))
    }
    return new Response(null, { status: 204 })
  })
  vi.stubGlobal('fetch', fetcher)
  const { SetCoachPasswordPage } = await import('./SetCoachPasswordPage')
  const navigate = vi.fn()
  await act(async () => root.render(<SetCoachPasswordPage navigate={navigate} />))
  input('password', 'SyntheticOnly093!'); input('confirm', 'SyntheticOnly093!')
  await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
  expect(navigate).not.toHaveBeenCalled()
  expect(host.querySelector('a[href="/coach/welcome"]')).toBeNull()
  expect(host.textContent).toContain('newcoach@example.test')
  input('signInPassword', 'SyntheticOnly093!')
  await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
  expect(navigate).toHaveBeenCalledWith('/coach/welcome')
  expect(JSON.parse(localStorage.getItem('mpw.user')!).id).toBe('new-user-b')
  const resets = fetcher.mock.calls.filter(([url]) => url.endsWith('/auth/email/reset'))
  expect(resets).toHaveLength(1)
  const logins = fetcher.mock.calls.filter(([url]) => url.endsWith('/auth/email/login'))
  expect(logins).toHaveLength(2)
  expect(logins.map(([, init]) => JSON.parse(init!.body as string).email)).toEqual(['newcoach@example.test', 'newcoach@example.test'])
})

